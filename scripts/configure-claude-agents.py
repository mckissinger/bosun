#!/usr/bin/env python3
"""Install Bosun's Claude agents at project scope with an explicit verifier effort."""

import argparse
import os
from pathlib import Path
import re
import shlex
import subprocess
import sys

MODEL = "claude-opus-5-5"

EFFORTS = ("low", "medium", "high", "xhigh", "max")
MARKER = "<!-- Generated by Bosun configure-claude-agents.py; edit the shipped templates instead. -->"
IGNORE_MARKER = "# Generated by Bosun configure-claude-agents.py"
# bosun-worker-opus was generated before 0.24.0; it stays ignored so an old copy does not show up in git.
GENERATED = ("bosun-scout", "bosun-verifier", "bosun-verifier-mobile", "bosun-worker-opus")
# Only the generated names: a glob such as bosun-*.md would also hide agents the user writes.
IGNORE_CONTENT = (
    f"{IGNORE_MARKER}: the agents below are regenerated, so git ignores them.\n"
    + "".join(f"/{name}.md\n" for name in GENERATED)
    + "/.gitignore\n"
)


def read_text_or_none(path):
    """Return the file's text, or None when it is not UTF-8 (then it is the user's, left alone)."""
    try:
        return path.read_text()
    except UnicodeDecodeError:
        return None


def configure(args):
    project = Path(args.project).resolve(strict=True)
    if not project.is_dir():
        raise ValueError("--project must be a directory")
    directory = project / ".claude" / "agents"
    for path in (project / ".claude", directory):
        if path.is_symlink() or (path.exists() and not path.is_dir()):
            raise ValueError(f"refusing non-directory or symlink: {path}")
    model = MODEL
    names = ["bosun-scout", "bosun-verifier", "bosun-verifier-mobile"]
    templates = Path(__file__).resolve().parent.parent / "agents"
    pending = []
    for name in names:
        source = (templates / f"{name}.md").read_text()
        parts = source.split("---", 2)
        if len(parts) != 3 or parts[0]:
            raise ValueError(f"invalid agent frontmatter: {name}")
        parts[1], count = re.subn(r"^model: .+$", f"model: {model}", parts[1], flags=re.M)
        if count == 0:
            parts[1] += f"model: {model}\n"
        elif count != 1:
            raise ValueError(f"expected at most one model field: {name}")
        if name.startswith("bosun-verifier"):
            parts[1], count = re.subn(r"^effort: .+$", f"effort: {args.verifier_effort}", parts[1], flags=re.M)
            if count != 1:
                raise ValueError(f"expected exactly one effort field: {name}")
        content = "---".join(parts) + "\n" + MARKER + "\n"
        target = directory / f"{name}.md"
        if target.is_symlink():
            raise ValueError(f"refusing symlink: {target}")
        if target.exists() and (not target.is_file() or MARKER not in (read_text_or_none(target) or "")):
            raise ValueError(f"refusing to overwrite a user-owned agent: {target}")
        pending.append((target, content))
    ignore = directory / ".gitignore"
    if ignore.is_symlink() or (ignore.exists() and not ignore.is_file()):
        raise ValueError(f"refusing non-file or symlink: {ignore}")
    ignore_text = read_text_or_none(ignore) if ignore.exists() else ""
    ignore_owned = not ignore.exists() or (ignore_text is not None and IGNORE_MARKER in ignore_text)
    ignore_stale = ignore_owned and ignore_text != IGNORE_CONTENT
    if not args.dry_run and ignore_stale and ignore.exists() and not os.access(ignore, os.W_OK):
        raise ValueError(f"cannot update read-only {ignore}; make it writable or delete it, then rerun")
    # Validate every destination and template before changing anything.
    if not args.dry_run:
        directory.mkdir(parents=True, exist_ok=True)
    for target, content in pending:
        if not args.dry_run and (not target.exists() or target.read_text() != content):
            target.write_text(content)
        print(f"{'Would configure' if args.dry_run else 'Configured'} {target}")
    if args.dry_run and ignore_stale:
        if ignore.exists() and not os.access(ignore, os.W_OK):
            print(f"Would stop: {ignore} is read-only and out of date")
        else:
            print(f"Would update {ignore}")
    if not ignore_owned:
        names_list = " ".join(f"{name}.md" for name in GENERATED)
        print(f"Left {ignore} alone (not Bosun's); add {names_list} to it to keep generated agents out of git")
    elif not args.dry_run and ignore_stale:
        ignore.write_text(IGNORE_CONTENT)
    try:
        tracked = subprocess.run(
            ["git", "-C", str(project), "ls-files", "-z", "--"]
            + [f".claude/agents/{name}.md" for name in GENERATED],
            capture_output=True, text=True,
        ).stdout.split("\0")
        tracked = [path for path in tracked if path]
    except OSError:  # no git on PATH: nothing to report
        tracked = []
    if tracked:
        quoted = " ".join(shlex.quote(path) for path in tracked)
        print(f"Git still tracks generated agents: {quoted}; to stop, run: git -C {shlex.quote(str(project))} rm --cached {quoted}")
    print(f"Verifier: {model} / {args.verifier_effort}")
    print(f"Scout: {model} / medium")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", required=True, help="Project root (contains the spec)")
    parser.add_argument("--mode", choices=("opus",), default="opus", help="Accepted for older callers; opus is the only mode")
    parser.add_argument("--verifier-effort", choices=EFFORTS, default="high")
    parser.add_argument("--dry-run", action="store_true", help="Validate and print targets without writing")
    args = parser.parse_args()
    try:
        configure(args)
    except (OSError, ValueError) as error:
        print(f"configure-claude-agents: {error}", file=sys.stderr)
        return 2
    return 0


if __name__ == "__main__":
    sys.exit(main())
